#!/usr/bin/env python3
"""ps2_tables.json (from ps2_extract.py) -> src/game/ps2_layout_table.h and a readable comparison sheet.

PS2 pad channels, from the ps2pad poll fn_00103670 (libpad's report into bytes 0xD..0x24 of its state):
  1 Select 2 Start 3 L3 4 R3 5 Right 6 Left 7 Up 8 Down 9 Triangle 10 Circle 11 Cross 12 Square
  13 L1 14 R1 15 L2 16 R2 17/18 right stick left/right 19/20 right stick up/down
  21/22 left stick left/right 23/24 left stick up/down          (5-16 pressure 0-255 when the pad has it)
For a PlayStation pad, ps_controls puts each button on the Xbox channel of the button in the same place (Cross A,
Circle B, Square X, Triangle Y, L1/R1 the triggers, L2/R2 White/Black, Select Back), so the alias entries
(0xED..0x104) are translated through PS2_TO_XBOX; they come out the same as the Xbox's own.
usage: gen_ps2_table.py ps2_tables.json xbox_tables.json out_header out_sheet [mvp05|mvp06]
  mvp05 (default): SLUS_211.35, 0x10A entries written, aliases 0xED..0x104
  mvp06: SLUS_213.67 (defaults fn_00457B38, layout fn_00100AB0), 0x111 entries, aliases 0xF4..0x10B; the Xbox
         tables from default.xbe (defaults fn_0028B1D0, Xbox layout fn_00318190, vtable slot +0x98)
"""
import json, sys

PS2_TO_XBOX = {1: 6, 2: 5, 3: 7, 4: 8, 5: 4, 6: 3, 7: 1, 8: 2, 9: 12, 10: 10, 11: 9, 12: 11, 13: 15, 14: 16,
               15: 14, 16: 13, 17: 22, 18: 21, 19: 23, 20: 24, 21: 18, 22: 17, 23: 19, 24: 20}
XB_CH = {1: 'D-Up', 2: 'D-Down', 3: 'D-Left', 4: 'D-Right', 5: 'Start', 6: 'Select/Back', 7: 'L3', 8: 'R3',
         9: 'Cross/A', 10: 'Circle/B', 11: 'Square/X', 12: 'Triangle/Y', 13: 'R2/Black', 14: 'L2/White',
         15: 'L1/LT', 16: 'R1/RT', 17: 'LS right', 18: 'LS left', 19: 'LS up', 20: 'LS down', 21: 'RS right',
         22: 'RS left', 23: 'RS up', 24: 'RS down'}
MODES = {0: 'press', 1: 'release', 2: 'hold', 3: 'mode3', 4: 'repeat', 5: 'analog'}
OPS = {-1: '', 0: '{a} or {b}', 1: '{a} + {b}', 2: '{a} (without {b})', 3: '{a} minus {b}', 4: 'while {a}: {b}',
       5: 'unless {a}: {b}'}
GAMES = {'mvp05': dict(n=0x10A, alias=0xED, title='MVP Baseball 2005', slus='SLUS_211.35',
                       funcs='the shared\n// defaults fn_0043CF70, then the ps2pad layout fn_00102F70'),
         'mvp06': dict(n=0x111, alias=0xF4, title='MVP 06 NCAA Baseball', slus='SLUS_213.67',
                       funcs='the shared\n// defaults fn_00457B38, then the ps2pad layout fn_00100AB0')}
N, A0 = 0x10A, 0xED


def main():
    global N, A0
    g = GAMES[sys.argv[5] if len(sys.argv) > 5 else 'mvp05']
    N, A0 = g['n'], g['alias']
    p = json.load(open(sys.argv[1])); x = json.load(open(sys.argv[2]))
    ps = {int(k): (v['shorts'][:5], v['scale']) for k, v in p['defaults']['table'].items()}
    for k, v in p['ps2_layout']['table'].items(): ps[int(k)] = (v['shorts'][:5], v['scale'])
    xb = {int(k): (v[0][:5], 1.0) for k, v in x['defaults'].items()}
    for k, v in x['xbox'].items(): xb[int(k)] = (v[0][:5], v[1])
    out = []
    for i in range(N):
        (a, b, ma, mb, op), sc = ps[i]
        if A0 <= i < A0 + 24 and a > 0: a = PS2_TO_XBOX[a]
        if abs(sc) > 1e6: sc = 1.0  # never written: the constructor's 1.0
        out.append((a, b, ma, mb, op, sc))
    alias = [out[i][0] for i in range(A0, A0 + 24)]
    assert alias == [xb[i][0][0] for i in range(A0, A0 + 24)], alias  # the same buttons in the same places
    with open(sys.argv[3], 'w') as f:
        f.write('// The PS2 release\'s action table: generated by tools/ps2_layout/gen_ps2_table.py from %s (%s). Virtual-button aliases (0x%X..0x%X) are\n' % (g['slus'], g['funcs'], A0, A0 + 23) +
                '// translated to the Xbox channels ps_controls puts each PlayStation button on (the same as the Xbox\'s).\n'
                '#pragma once\n#include <cstdint>\n\n#include "gc_layout_table.h"\n\nnamespace ps {\n'
                'constexpr uint32_t kPsEntries = 0x%X;\nconstexpr gc::Entry kPsTable[kPsEntries] = {\n' % N)
        for i, e in enumerate(out):
            f.write('    {%d, %d, %d, %d, %d, %sf},  // 0x%03X\n' % (*e[:5], repr(float(e[5])), i))
        f.write('};\n}  // namespace ps\n')

    def describe(e):
        (a, b, ma, mb, op) = e[:5]
        def one(v, m):
            if v == -2: return 'unbound'
            if v == -1: return 'nothing'
            if v > 24 or v == 0: return 'action 0x%X' % v
            return '%s [%s]' % (XB_CH[alias[v - 1]], MODES.get(m, m))
        if a == -2: return 'unbound'
        return one(a, ma) if op == -1 else OPS[op].format(a=one(a, ma), b=one(b, mb))
    lines = ['%s: every action the PS2 release binds differently from the Xbox release' % g['title'],
             'Buttons named by place: Cross/A, Circle/B, Square/X, Triangle/Y, L1/LT, R1/RT, L2/White, R2/Black.', '',
             'Action  Xbox                                           PS2']
    for i in range(A0):
        dx, dp = describe(xb[i][0]), describe(out[i])
        if dx != dp: lines.append('0x%03X   %-46s %s' % (i, dx, dp))
    open(sys.argv[4], 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


main()
