#!/usr/bin/env python3
"""The EXPERIMENTAL GameCube action table for MVP 06 (there was no GameCube release) -> src/game/gc_layout_table.h

usage: gen_table06.py gc_tables.json(05 GC) xbox_tables_mvp06.json gc06_draft.json(from draft_gc06.py) out_header

The action entries (0x000..0x0F3) come from draft_gc06.py: the real MVP 2005 GameCube binding where an 06 action
matches a 05 one, else a proposal. The virtual-button aliases (06: 0xF4..0x10B) are the 05 GameCube release's
(0xED..0x104), each GameCube button put on the Xbox channel gc_controls.cpp gives it (GC_TO_XBOX, as gen_table.py).
The entries after them are the 06 Xbox's. Scales: the 06 Xbox's (both releases leave them 1.0 but a few).
"""
import json, sys

GC_TO_XBOX = {1: 4, 2: 3, 3: 2, 4: 1, 5: 14, 6: 9, 7: 10, 8: 11, 9: 12, 10: 5, 11: 15, 12: 16,
              13: 17, 14: 18, 15: 19, 16: 20, 17: 21, 18: 22, 19: 23, 20: 24}
N, A5, A6 = 0x111, 0xED, 0xF4


def main():
    g = json.load(open(sys.argv[1])); x = json.load(open(sys.argv[2])); d = json.load(open(sys.argv[3]))
    gc5 = {int(k): v['shorts'][:5] for k, v in g['defaults']['table'].items()}
    for k, v in g['gc_layout']['table'].items(): gc5[int(k)] = v['shorts'][:5]
    xb = {int(k): (v[0][:5], 1.0) for k, v in x['defaults'].items()}
    for k, v in x['xbox'].items(): xb[int(k)] = (v[0][:5], v[1])
    draft = {int(k): v for k, v in d['gc06'].items()}
    src = {int(k): v for k, v in d['source'].items()}
    out = []
    for i in range(N):
        sc = xb[i][1] if abs(xb[i][1]) < 1e6 else 1.0
        if i < A6:
            e = list(draft[i]); note = src[i]
        elif i < A6 + 24:
            a, b, ma, mb, op = gc5[A5 + i - A6]
            e = [GC_TO_XBOX[a] if a > 0 else a, b, ma, mb, op]; note = 'alias v%d (05 GC 0x%03X)' % (i - A6 + 1, A5 + i - A6)
        else:
            e = list(xb[i][0]); note = '06 Xbox'
        out.append((e, sc, note))
    with open(sys.argv[4], 'w') as f:
        f.write('// EXPERIMENTAL: a GameCube action table for MVP 06 NCAA, which had no GameCube release. Generated by\n'
                '// tools/gc_layout/gen_table06.py: actions that match MVP 2005 take the 2005 GameCube release\'s binding, new 06\n'
                '// actions are proposals (tools/gc_layout/gamecube_vs_xbox_mvp06_DRAFT.txt); virtual-button aliases (0x%X..0x%X)\n'
                '// are the 2005 GameCube\'s, translated to the Xbox channels gc_controls.cpp puts each GameCube button on.\n'
                '#pragma once\n#include <cstdint>\n\nnamespace gc {\nstruct Entry {\n    int16_t a, b, mode_a, mode_b, op;\n'
                '    float scale;\n};\nconstexpr bool kHaveGcTable = true;\nconstexpr uint32_t kGcEntries = 0x%X;\n'
                'constexpr Entry kGcTable[kGcEntries] = {\n' % (A6, A6 + 23, N))
        for i, (e, sc, note) in enumerate(out):
            f.write('    {%d, %d, %d, %d, %d, %sf},  // 0x%03X %s\n' % (*e, repr(float(sc)), i, note))
        f.write('};\n}  // namespace gc\n')
    print('wrote', sys.argv[4], N, 'entries')


main()
